"""D(Dic_3) ordinary split CP2#2CPbar character scan.

Dic_3 is the order-12 dicyclic group, also called the binary dihedral group
of order 12 and sometimes denoted Q12:

    <a,x | a^6=1, x^2=a^3, x^-1 a x=a^-1>.

This script uses only the untwisted finite-group double formulas.  It scans
the cyclic subgroup generated by the invertible object g=(a^3, chi), where
chi(x)=i and chi(a)=-1.
"""

from __future__ import annotations

from datetime import UTC, datetime
from itertools import product
import cmath
import json
import math
from pathlib import Path
import subprocess
import sys
import time


REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT = (
    REPO_ROOT
    / "experiments"
    / "results"
    / "yasui"
    / "cp2-2cpbar-dg-dic3-split-character-scan-v1.json"
)
STANDARD_ORDER = ("h", "e1", "e2")
STANDARD_FRAMINGS = (1, -1, -1)
TOLERANCE = 1e-9


def command(argv: list[str]) -> str | None:
    try:
        return subprocess.check_output(argv, cwd=REPO_ROOT, text=True, stderr=subprocess.DEVNULL).strip()
    except (FileNotFoundError, subprocess.CalledProcessError):
        return None


def rel(path: Path) -> str:
    return str(path.resolve().relative_to(REPO_ROOT))


def complex_json(value: complex) -> dict[str, str]:
    value = complex(value)
    return {
        "field": "complex128",
        "real": repr(float(value.real)),
        "imag": repr(float(value.imag)),
        "abs": repr(float(abs(value))),
        "display": f"{value.real:.17g}{value.imag:+.17g}j",
    }


def root(order: int, power: int) -> complex:
    return cmath.exp(2j * math.pi * power / order)


def dic3_double_simples() -> list[dict]:
    simples: list[dict] = []

    # Full Dic_3 irreps for the central classes 1 and a^3.  One-dimensional
    # irreps factor through Dic_3_ab = C4, generated by x.
    full_irreps = []
    for m in range(4):
        x_value = root(4, m)
        a_value = x_value**2
        full_irreps.append(
            {
                "name": f"lin_x_m{m}",
                "dim": 1,
                "lambda_a3": a_value,
            }
        )
    for j in (1, 2):
        full_irreps.append(
            {
                "name": f"two_dim_j{j}",
                "dim": 2,
                "lambda_a3": (-1) ** j,
            }
        )
    for class_name, representative, chi_c, twist_lambda in (
        ("1", "1", 1, lambda rep: 1),
        ("a3", "a^3", -1, lambda rep: rep["lambda_a3"]),
    ):
        for rep in full_irreps:
            dim = rep["dim"]
            simples.append(
                {
                    "class": class_name,
                    "representative": representative,
                    "centralizer": "Dic_3",
                    "irrep": rep["name"],
                    "irrep_dim": dim,
                    "quantum_dimension": dim,
                    "twist": complex(twist_lambda(rep)),
                    "witness_chi_on_class": complex(chi_c),
                    "witness_z_scalar": complex(rep["lambda_a3"]),
                }
            )

    # Rotation classes {a,a^-1} and {a^2,a^-2}; centralizer <a> = C6.
    for class_name, representative, class_size, exponent, chi_c in (
        ("a_a5", "a", 2, 1, -1),
        ("a2_a4", "a^2", 2, 2, 1),
    ):
        for m in range(6):
            simples.append(
                {
                    "class": class_name,
                    "representative": representative,
                    "centralizer": "C6=<a>",
                    "irrep": f"char_m{m}",
                    "irrep_dim": 1,
                    "quantum_dimension": class_size,
                    "twist": root(6, m * exponent),
                    "witness_chi_on_class": complex(chi_c),
                    "witness_z_scalar": complex((-1) ** m),
                }
            )

    # Two x-type conjugacy classes, each with C4 centralizer generated by a^i x.
    for class_name, representative, chi_c in (
        ("even_x_class", "x", 1j),
        ("odd_x_class", "a x", -1j),
    ):
        for m in range(4):
            simples.append(
                {
                    "class": class_name,
                    "representative": representative,
                    "centralizer": "C4=<representative>",
                    "irrep": f"char_m{m}",
                    "irrep_dim": 1,
                    "quantum_dimension": 3,
                    "twist": root(4, m),
                    "witness_chi_on_class": complex(chi_c),
                    "witness_z_scalar": complex((-1) ** m),
                }
            )

    return simples


def monodromy(simple: dict, witness_power: int) -> complex:
    return (simple["witness_chi_on_class"] * simple["witness_z_scalar"]) ** witness_power


def gauss(simples: list[dict], framing: int, witness_power: int) -> complex:
    total = 0j
    for simple in simples:
        dim = simple["quantum_dimension"]
        total += dim * dim * monodromy(simple, witness_power) * simple["twist"] ** framing
    return total


def repo_metadata() -> dict:
    status_short = command(["git", "status", "--short"])
    return {
        "root": str(REPO_ROOT),
        "git_commit": command(["git", "rev-parse", "HEAD"]),
        "dirty": bool(status_short),
        "status_short": status_short,
    }


def main() -> int:
    started = time.monotonic()
    utc_start = datetime.now(UTC).isoformat()
    simples = dic3_double_simples()
    labels = range(4)
    one_component = {
        str(framing): {
            str(label): complex_json(gauss(simples, framing, label))
            for label in labels
        }
        for framing in (-1, 1)
    }
    baseline = (
        gauss(simples, 1, 0)
        * gauss(simples, -1, 0)
        * gauss(simples, -1, 0)
    )
    rows = []
    for alpha in product(labels, repeat=3):
        factors = [
            gauss(simples, framing, label)
            for framing, label in zip(STANDARD_FRAMINGS, alpha, strict=True)
        ]
        value = factors[0] * factors[1] * factors[2]
        predicted_ratio = (-1) ** (-alpha[0] + alpha[1] + alpha[2])
        ratio = value / baseline
        rows.append(
            {
                "standard_alpha_order": list(STANDARD_ORDER),
                "standard_alpha": list(alpha),
                "standard_framings": list(STANDARD_FRAMINGS),
                "component_factors": [complex_json(factor) for factor in factors],
                "raw_value": complex_json(value),
                "baseline_ratio": complex_json(ratio),
                "predicted_ratio_from_witness_twist": predicted_ratio,
                "ratio_prediction_error": complex_json(ratio - predicted_ratio),
                "differs_from_baseline": bool(abs(ratio - 1) > TOLERANCE),
            }
        )
    nonbaseline = [row for row in rows if row["differs_from_baseline"]]
    max_ratio_prediction_error = max(
        abs(
            complex(
                float(row["ratio_prediction_error"]["real"]),
                float(row["ratio_prediction_error"]["imag"]),
            )
        )
        for row in rows
    )
    payload = {
        "schema": "twisted-yetter.cp2-2cpbar-dg-dic3-split-character-scan.v1",
        "status": "pass" if max_ratio_prediction_error < TOLERANCE else "mismatch",
        "generator_script": rel(Path(__file__)),
        "argv": sys.argv[1:],
        "reproduce_command": "python experiments/sage/dg_dic3_split_character_scan.py",
        "utc_start": utc_start,
        "utc_finish": datetime.now(UTC).isoformat(),
        "elapsed_seconds": time.monotonic() - started,
        "repo": repo_metadata(),
        "group": {
            "name": "Dic_3",
            "aliases": ["dicyclic group of order 12", "binary dihedral group of order 12", "Q12 in some conventions"],
            "presentation": "<a,x | a^6=1, x^2=a^3, x^-1 a x=a^-1>",
            "order": 12,
            "center": "<a^3> = C2",
            "commutator_subgroup": "<a^2> = C3",
            "abelianization": "C4",
            "nonproduct_note": "This is the natural order-12 non-cartesian-product witness group for the split D(G) phase criterion.",
        },
        "category": {
            "id": "D(Dic_3)_untwisted",
            "global_dimension": 144,
            "simple_count": len(simples),
            "simple_dimension_square_sum": sum(simple["quantum_dimension"] ** 2 for simple in simples),
            "simple_data": [
                {
                    key: (complex_json(value) if isinstance(value, complex) else value)
                    for key, value in simple.items()
                }
                for simple in simples
            ],
        },
        "witness_invertible": {
            "label": "g=(a^3, chi)",
            "chi": "chi(x)=i, chi(a)=-1",
            "order": 4,
            "twist": -1,
        },
        "case": {
            "manifold": "CP2#2CPbar",
            "presentation": "ordinary split unlink",
            "standard_component_order": list(STANDARD_ORDER),
            "standard_framings": list(STANDARD_FRAMINGS),
            "character_subgroup_scanned": "Z/4 generated by g on each component",
        },
        "one_component_gauss_sums": one_component,
        "baseline_raw_value": complex_json(baseline),
        "row_count": len(rows),
        "nonbaseline_count": len(nonbaseline),
        "nonbaseline_alphas": [row["standard_alpha"] for row in nonbaseline],
        "max_ratio_prediction_error": repr(float(max_ratio_prediction_error)),
        "rows": rows,
        "claim_boundary": (
            "Direct ordinary split-link test for D(Dic_3) using finite-group "
            "double simple-object dimensions and twists. This does not evaluate "
            "a non-separated Yasui braid presentation."
        ),
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    print(
        json.dumps(
            {
                "artifact": rel(OUTPUT),
                "status": payload["status"],
                "baseline_raw_value": payload["baseline_raw_value"]["display"],
                "row_count": len(rows),
                "nonbaseline_count": len(nonbaseline),
                "first_nonbaseline_alphas": payload["nonbaseline_alphas"][:8],
            },
            sort_keys=True,
        )
    )
    return 0 if payload["status"] == "pass" else 1


if __name__ == "__main__":
    raise SystemExit(main())
