"""SU(2)_6 colored-Jones Kirby-slide stress suite.

Run from the repository root:

    DOT_SAGE="$PWD/.sage" sage experiments/sage/su2_6_kirby_slide_stress.sage.py

This suite checks a bounded but genuinely nontrivial Kirby-move class:

* one nontrivial knot component is represented as a one-component braid closure;
* it is colored by Omega_a for SU(2)_6;
* it is slid over one or more split framed unknots colored by Omega_b;
* after the slide, the knot framing changes and the slide-over components are
  meridians of the knot, evaluated by the modular S-matrix meridian action.

The fixed-label knot values use Sage's reduced colored Jones polynomial,
calibrated by the SU(2)_2 trefoil convention already used in this repo:

    RT_j(K, framing f) = d_j * J_{j+1}(K; q=A^4) * theta_j^f.

This is not an arbitrary multi-component colored-link evaluator.  It is a
Kirby-slide stress suite for the meridian-link class generated by sliding a
single knot over split framed unknots.
"""

