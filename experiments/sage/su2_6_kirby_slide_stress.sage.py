def run_suite():
    validate_knot_inputs()
    normalization_controls = colored_jones_normalization_controls()
    comparisons = []
    nontriviality_controls = []
    knot_value_cache = {}
    for knot in KNOT_CASES:
        knot_values = cached_colored_jones_root_values(knot_value_cache, knot)
        nontriviality_controls.append(nontrivial_knot_control(knot, knot_values))
        for scenario in SLIDE_SCENARIOS:
            comparisons.extend(slide_comparisons(knot, scenario, knot_values))

    status = "pass"
    if any(item["status"] != "pass" for item in normalization_controls):
        status = "fail"
    if any(item["status"] != "pass" for item in nontriviality_controls):
        status = "fail"
    if any(item["status"] != "pass" for item in comparisons):
        status = "fail"

    return {
        "schema": "twisted-yetter.su2-6-kirby-slide-stress.v1",
        "status": status,
        "category_id": "SU(2)_6",
        "claim_level": "computed Kirby-slide evidence for meridian-link class / not arbitrary evaluator",
        "scope": (
            "single nontrivial knot braid closure slid over split framed unknots; "
            "fixed-label knot values from Sage colored Jones; meridian components "
            "evaluated by SU(2)_6 S-matrix action"
        ),
        "not_scope": (
            "arbitrary multi-component colored link evaluator, arbitrary planar diagram, "
            "general band-sum constructor, dotted/special links, closed 4-manifold "
            "normalization, or exotic-pair computation"
        ),
        "normalization_controls": normalization_controls,
        "nontriviality_controls": nontriviality_controls,
        "comparison_count": len(comparisons),
        "knot_count": len(KNOT_CASES),
        "scenario_count": len(SLIDE_SCENARIOS),
        "unique_colored_jones_braid_count": len(knot_value_cache),
        "comparisons": comparisons,
    }


def slide_comparisons(knot, scenario, knot_values):
    comparisons = []
    component_count = 1 + len(scenario["slide_framings"])
    for omega_labels in product((0, 1), repeat=component_count):
        before = before_slide_value(knot, scenario, omega_labels, knot_values)
        after = after_slide_value(knot, scenario, omega_labels, knot_values)
        comparisons.append(
            {
                "name": f"{knot['name']}::{scenario['name']}::omega={','.join(map(str, omega_labels))}",
                "knot": knot_payload(knot),
                "scenario": scenario_payload(scenario),
                "omega_labels_before": [int(label) for label in omega_labels],
                "omega_labels_after": [int(after_knot_omega_label(omega_labels))]
                + [int(label) for label in omega_labels[1:]],
                "before_value": cyclotomic_json(before),
                "after_value": cyclotomic_json(after),
                "difference": cyclotomic_json(before - after),
                "status": "pass" if before == after else "fail",
            }
        )
    return comparisons


def before_slide_value(knot, scenario, omega_labels, knot_values):
    total = FIELD(0)
    knot_omega = omega_labels[0]
    slide_omegas = omega_labels[1:]
    for knot_label in LABELS:
        total += (
            omega_coefficient(knot_omega, knot_label)
            * framed_knot_value(knot, knot_label, knot["knot_framing"], knot_values)
            * split_unlink_omega_value(scenario["slide_framings"], slide_omegas)
        )
    return FIELD(total)


def after_slide_value(knot, scenario, omega_labels, knot_values):
    total = FIELD(0)
    slide_framings = scenario["slide_framings"]
    transformed_knot_omega = after_knot_omega_label(omega_labels)
    slide_omegas = omega_labels[1:]
    transformed_knot_framing = knot["knot_framing"] + sum(slide_framings)
    for knot_label in LABELS:
        meridian_product = FIELD(1)
        for slide_framing, slide_omega in zip(slide_framings, slide_omegas, strict=True):
            meridian_product *= meridian_omega_value(slide_framing, slide_omega, knot_label)
        knot_factor = (
            omega_coefficient(transformed_knot_omega, knot_label)
            * framed_knot_value(knot, knot_label, transformed_knot_framing, knot_values)
        )
        total += knot_factor * meridian_product
    return FIELD(total)


def split_unlink_omega_value(slide_framings, slide_omegas):
    value = FIELD(1)
    for framing, omega_label in zip(slide_framings, slide_omegas, strict=True):
        summand = FIELD(0)
        for label in LABELS:
            summand += omega_coefficient(omega_label, label) * dimension(label) * twist(label) ** framing
        value *= summand
    return FIELD(value)


def meridian_omega_value(slide_framing, slide_omega, knot_label):
    return FIELD(
        sum(
            omega_coefficient(slide_omega, slide_label)
            * twist(slide_label) ** slide_framing
            * meridian_action(slide_label, knot_label)
            for slide_label in LABELS
        )
    )


def after_knot_omega_label(omega_labels):
    return sum(omega_labels) % 2


def omega_coefficient(omega_label, simple_label):
    return FIELD(dimension(simple_label) * ((-1) ** (omega_label * degree(simple_label))))


def framed_knot_value(knot, label, framing, knot_values):
    return FIELD(dimension(label) * knot_values[label] * twist(label) ** framing)


def colored_jones_root_values(knot):
    braid_group = BraidGroup(knot["n_strands"])
    braid = braid_group(list(knot["braid_word"]))
    return {
        label: FIELD(braid.colored_jones_polynomial(label + 1)(JONES_Q))
        for label in LABELS
    }


def cached_colored_jones_root_values(cache, knot):
    key = (int(knot["n_strands"]), tuple(int(generator) for generator in knot["braid_word"]))
    if key not in cache:
        cache[key] = colored_jones_root_values(knot)
    return cache[key]


def nontrivial_knot_control(knot, knot_values):
    non_unit_labels = [
        label
        for label in LABELS[1:]
        if knot_values[label] != FIELD(1)
    ]
    return {
        "name": f"{knot['name']}_colored_jones_nontrivial_at_root",
        "knot": knot_payload(knot),
        "non_unit_labels": [int(label) for label in non_unit_labels],
        "sample_values": {
            str(label): cyclotomic_json(knot_values[label])
            for label in LABELS[:4]
        },
        "status": "pass" if non_unit_labels else "fail",
    }


def colored_jones_normalization_controls():
    level2_field = CyclotomicField(16)
    zeta16 = level2_field.gen()
    sqrt2 = zeta16**2 + zeta16**(-2)
    braid = BraidGroup(2)([1, 1, 1])
    trefoil_label_one = level2_field(braid.colored_jones_polynomial(2)(zeta16**4))
    return [
        {
            "name": "sage_colored_jones_matches_su2_2_trefoil_calibration",
            "expected_reduced_colored_jones": cyclotomic_json_in_field(level2_field, -1, 16),
            "actual_reduced_colored_jones": cyclotomic_json_in_field(level2_field, trefoil_label_one, 16),
            "expected_rt_value_after_dimension": cyclotomic_json_in_field(level2_field, -sqrt2, 16),
            "actual_rt_value_after_dimension": cyclotomic_json_in_field(
                level2_field,
                sqrt2 * trefoil_label_one,
                16,
            ),
            "status": "pass" if trefoil_label_one == -1 else "fail",
        }
    ]


def validate_knot_inputs():
    for knot in KNOT_CASES:
        braid_group = BraidGroup(knot["n_strands"])
        braid = braid_group(list(knot["braid_word"]))
        component_count = Link(braid).number_of_components()
        if component_count != 1:
            raise ValueError(f"{knot['name']} closure must be a knot, got {component_count} components")


def knot_payload(knot):
    return {
        "name": knot["name"],
        "n_strands": int(knot["n_strands"]),
        "braid_word": [int(generator) for generator in knot["braid_word"]],
        "knot_framing": int(knot["knot_framing"]),
    }


def scenario_payload(scenario):
    return {
        "name": scenario["name"],
        "slide_framings": [int(framing) for framing in scenario["slide_framings"]],
        "move_model": (
            "before: split framed unknots; after: knot slid over all slide-over "
            "components, knot framing adds slide framings, and slide-over components "
            "become meridians of the knot"
        ),
    }


def dimension(label):
    return FIELD(q_sine(label + 1) / q_sine(1))


def twist(label):
    return FIELD(A_ROOT ** (label * (label + 2)))


def degree(label):
    return label % 2


def meridian_action(meridian_label, knot_label):
    return FIELD(q_sine((meridian_label + 1) * (knot_label + 1)) / q_sine(knot_label + 1))


def q_sine(multiplier):
    return FIELD((A_ROOT ** (2 * multiplier) - A_ROOT ** (-2 * multiplier)) / (A_ROOT**2 - A_ROOT**(-2)))


def cyclotomic_json(value):
    return cyclotomic_json_in_field(FIELD, FIELD(value), ROOT_ORDER)


def cyclotomic_json_in_field(field, value, root_order):
    value = field(value)
    return {
        "field": f"CyclotomicField({root_order})",
        "zeta_symbol": f"zeta{root_order}",
        "display": str(value),
        "coefficients": [str(coefficient) for coefficient in value.list()],
    }


def build_certificate(exact_output, output_path, started_at, elapsed_seconds):
    input_definition = {
        "suite": "su2-6-kirby-slide-stress-v1",
        "output_path": str(output_path.relative_to(REPO_ROOT)),
        "knot_cases": [knot_payload(knot) for knot in KNOT_CASES],
        "slide_scenarios": [scenario_payload(scenario) for scenario in SLIDE_SCENARIOS],
    }
    return make_certificate(
        status=exact_output["status"],
        command="sage experiments/sage/su2_6_kirby_slide_stress.sage.py",
        argv=[Path(sys.argv[0]).name, *sys.argv[1:]],
        git=git_metadata(),
        tool_versions={"python": sys.version.split()[0], "sage": SAGE_VERSION},
        input_hash=hash_json(input_definition),
        exact_output=exact_output,
        generator_script=str(Path(__file__).relative_to(REPO_ROOT)),
        reproduce_command=(
            'DOT_SAGE="$PWD/.sage" sage experiments/sage/su2_6_kirby_slide_stress.sage.py '
            f"--output {output_path.relative_to(REPO_ROOT)}"
        ),
        started_at_utc=started_at,
        finished_at_utc=utc_now_iso(),
        elapsed_seconds=int(elapsed_seconds),
        repo_root=str(REPO_ROOT),
        notes=[
            "This is a SU(2)_6 Kirby-slide stress suite for the meridian-link class.",
            "It is not an arbitrary colored-link or closed-four-manifold evaluator.",
        ],
    )


def git_metadata():
    return {
        "commit": _run(["git", "rev-parse", "HEAD"]),
        "dirty": bool(_run(["git", "status", "--porcelain"])),
    }


def utc_now_iso():
    return _run(["date", "-u", "+%Y-%m-%dT%H:%M:%SZ"])


def _run(command):
    return subprocess.run(
        command,
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    output_path = args.output
    if not output_path.is_absolute():
        output_path = REPO_ROOT / output_path
    output_path.parent.mkdir(parents=True, exist_ok=True)

    started_at = utc_now_iso()
    start = time.time()
    exact_output = run_suite()
    certificate = build_certificate(exact_output, output_path, started_at, time.time() - start)
    output_path.write_text(dumps_certificate(certificate))

    print(f"wrote {output_path.relative_to(REPO_ROOT)}")
    print(f"status: {exact_output['status']}")
    print(f"knots: {exact_output['knot_count']}")
    print(f"scenarios: {exact_output['scenario_count']}")
    print(f"comparisons: {exact_output['comparison_count']}")

    if exact_output["status"] != "pass":
        raise SystemExit(1)


if __name__ == "__main__":
    main()
